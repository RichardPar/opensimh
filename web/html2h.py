#!/usr/bin/env python3
"""Regenerate sim_web_page.h from web/blinkenlights.html.

    python3 web/html2h.py            (run from the top of the source tree)

The page is embedded as a byte array so there is no string-literal length
limit to trip over on older compilers.
"""
import os, sys

here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, "blinkenlights.html")
dst = os.path.join(here, "..", "sim_web_page.h")
data = open(src, "rb").read()
lines = []
for i in range(0, len(data), 16):
    lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]))
with open(dst, "w", newline="\n") as f:
    f.write("/* sim_web_page.h: GENERATED by web/html2h.py from web/blinkenlights.html -- do not edit */\n\n")
    f.write("static const unsigned char web_page_html[] = {\n")
    f.write(",\n".join(lines))
    f.write("\n    };\n\nstatic const size_t web_page_html_len = sizeof (web_page_html);\n")
# the makefile does not list generated headers as prerequisites: touch the includer
os.utime(os.path.join(here, "..", "sim_web.c"), None)
print("wrote %s (%d bytes of HTML)" % (os.path.normpath(dst), len(data)))
